#!/usr/bin/env python3
"""Writes a synthetic Roc program with the shape of the SDK's engine: a dispatcher called with
known constructors (`Ok(st)` and `Err(NoState)`), N handlers each called at one site, small
helpers that take the parts of a known record, and a loop that drives it all.

  gen_repro.py N plain   > repro_plain.roc     # handlers as written naturally
  gen_repro.py N return  > repro_return.roc    # same, each handler starts with an early `return`

The two programs compute the same thing. Build both with `roc build --timings` (opt=speed).
"""
import sys

n = int(sys.argv[1])
mode = sys.argv[2]
out = []
w = out.append
w("# Generated by gen_repro.py %d %s. Headerless: runs on the built-in Echo platform." % (n, mode))
w("")
w("Parts : { names : List(Str), limit : U64, tag : Str, verbose : Bool }")
w("")
w("Step : { out : List(Str), count : U64, log : List(Str) }")
w("")
w("reply : List(Str) -> Step")
w("reply = |lines| { out: lines, count: 0, log: [] }")
w("")
w("line : Parts, Str, Str -> Str")
w("line = |parts, method, text| if parts.verbose \"${parts.tag}:${method}:${text}\" else text")
w("")
w("allowed : Try(U64, [NoState]), U64 -> Bool")
w("allowed = |maybe, k| match maybe {")
w("\tOk(st) => st % (k + 2) != 1")
w("\tErr(NoState) => Bool.True")
w("}")
w("")
for i in range(n):
    w("handler_%d : Parts, Try(U64, [NoState]), Str -> Step" % i)
    if mode == "return":
        w("handler_%d = |parts, maybe, text| {" % i)
        w("\tif text == \"\" {")
        w("\t\treturn reply([])")
        w("\t}")
    else:
        w("handler_%d = |parts, maybe, text| {" % i)
    w("\tif !(allowed(maybe, %d)) {" % i)
    w("\t\t{ ..reply([line(parts, \"m%d\", \"disabled\")]), log: [\"m%d disabled\"] }" % (i, i))
    w("\t} else {")
    w("\t\tpicked = parts.names.keep_if(|x| x.count_utf8_bytes() > %d).map(|x| line(parts, \"m%d\", \"${x}${text}\"))" % (i % 5, i))
    w("\t\tmatch picked.first() {")
    w("\t\t\tOk(f) if parts.limit > %d => { ..reply(picked), count: picked.len(), log: [f] }" % i)
    w("\t\t\tOk(_) => reply([line(parts, \"m%d\", \"over\")])" % i)
    w("\t\t\tErr(_) => reply([line(parts, \"m%d\", \"none\")])" % i)
    w("\t\t}")
    w("\t}")
    w("}")
    w("")
w("dispatch : Parts, Try(U64, [NoState]), U64, Str -> Step")
w("dispatch = |parts, maybe, method, text| match method {")
for i in range(n):
    w("\t%d => handler_%d(parts, maybe, text)" % (i, i))
w("\t_ => reply([line(parts, \"?\", \"not found\")])")
w("}")
w("")
w("receive : Parts, U64, U64, Str -> Step")
w("receive = |parts, st, method, text| {")
w("\tfirst = dispatch(parts, Ok(st), method, text)")
w("\tif first.count > 3 dispatch(parts, Err(NoState), method + 1, text) else first")
w("}")
w("")
w("main! = |args| {")
w("\tparts = { names: args, limit: args.len(), tag: \"t\", verbose: args.len() > 2 }")
w("\tvar $st = 0.U64")
w("\tfor a in args {")
w("\t\tstep = receive(parts, $st, a.count_utf8_bytes(), a)")
w("\t\t$st = $st + step.count")
w("\t\tfor l in step.out {")
w("\t\t\techo!(l)")
w("\t\t}")
w("\t}")
w("\tOk({})")
w("}")
print("\n".join(out))
